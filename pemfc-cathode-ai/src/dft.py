"""DFT layer: adsorption energies -> ORR free-energy steps -> limiting potential -> ranking inputs.

What this module is, and is not
-------------------------------
* It turns **adsorption energies of OH, O and OOH** (eV, referenced to H2O and H2) into the
  four-step associative ORR free-energy diagram with the **computational hydrogen electrode (CHE)**,
  the **theoretical limiting potential** U_L and the **overpotential** eta = 1.23 V - U_L.
* It does **not** compute DFT. DFT energies come from (a) your own calculations (``src/dft_jobs.py``),
  (b) a public database (``src/dft_data.py``) or (c) a CSV you supply. Every row carries a
  ``provenance`` tag and the product refuses to *recommend* a candidate from untrusted provenance.
* The zero-point and entropy corrections below are the commonly used CHE values; they depend on your
  functional, solvation model and coverage. Treat them as defaults to verify, not as truth.

Energies in eV, potentials in V vs the standard hydrogen electrode (SHE).
"""
from __future__ import annotations

import re
from dataclasses import dataclass

import numpy as np
import pandas as pd

# --------------------------------------------------------------------------- provenance
PROVENANCE = ("dft", "mlip", "literature_user", "emt_toy", "synthetic_demo", "ml_predicted")
TRUSTED = {"dft", "mlip", "literature_user"}        # may support a recommendation
PROVENANCE_NOTE = {
    "dft": "calculated with DFT by you or taken from a database record (cite the source)",
    "mlip": "machine-learned interatomic potential: fast, approximate, check against DFT",
    "literature_user": "values you copied from a publication (cite it in `reference`)",
    "emt_toy": "ASE EMT toy potential: tests the workflow only, chemically meaningless for adsorption",
    "synthetic_demo": "generated by a toy model so the app runs: NOT a result",
    "ml_predicted": "predicted by this project's ML model: never a calculated or measured value",
}

# --------------------------------------------------------------------------- CHE constants
G_O2_TO_2H2O = 4.92            # eV: 4 x 1.23 V, experimental free energy of 2 H2 + O2 -> 2 H2O (CHE reference)
U_EQ = 1.23                    # V, equilibrium potential
CHE_CORR = {"OH": 0.35, "O": 0.05, "OOH": 0.40}   # eV, commonly used (ZPE - T*dS) corrections: verify
OOH_OH_OFFSET = 3.2            # eV, widely reported scaling offset dG_OOH ~ dG_OH + 3.2 (+- ~0.2)
REQUIRED_COLS = ["system_id", "composition", "facet", "E_OH", "E_O", "E_OOH", "provenance"]
OPTIONAL_COLS = ["structure", "d_band_center", "formation_energy", "surface_energy", "segregation_energy",
                 "dissolution_potential", "functional", "code", "reference"]


def free_energies(df: pd.DataFrame, corr: dict | None = None) -> pd.DataFrame:
    """Add dG_OH, dG_O, dG_OOH (eV) from the raw adsorption energies."""
    c = {**CHE_CORR, **(corr or {})}
    out = df.copy()
    out["dG_OH"] = out["E_OH"] + c["OH"]
    out["dG_O"] = out["E_O"] + c["O"]
    out["dG_OOH"] = out["E_OOH"] + c["OOH"]
    return out


def orr_steps(dG_OH, dG_O, dG_OOH) -> np.ndarray:
    """The four reaction free energies at U = 0 V (eV): shape (..., 4).

    1) O2 + * + (H+ + e-)  -> *OOH      dG1 = dG_OOH - 4.92
    2) *OOH + (H+ + e-)    -> *O + H2O  dG2 = dG_O - dG_OOH
    3) *O + (H+ + e-)      -> *OH       dG3 = dG_OH - dG_O
    4) *OH + (H+ + e-)     -> * + H2O   dG4 = -dG_OH      (the four add up to -4.92 eV)
    """
    a, b, c = (np.asarray(x, float) for x in (dG_OH, dG_O, dG_OOH))
    return np.stack([c - G_O2_TO_2H2O, b - c, a - b, -a], axis=-1)


def limiting_potential(dG_OH, dG_O, dG_OOH):
    """U_L = -max(dG_i): the highest potential at which every step is downhill."""
    return -orr_steps(dG_OH, dG_O, dG_OOH).max(axis=-1)


def add_orr_metrics(df: pd.DataFrame) -> pd.DataFrame:
    out = free_energies(df)
    steps = orr_steps(out.dG_OH, out.dG_O, out.dG_OOH)
    out[["step1", "step2", "step3", "step4"]] = steps
    out["U_L"] = -steps.max(axis=1)
    out["eta"] = U_EQ - out["U_L"]
    out["limiting_step"] = steps.argmax(axis=1) + 1
    return out


def free_energy_diagram(row: pd.Series, U: float = 0.0) -> pd.DataFrame:
    """Cumulative free-energy levels of the 5 states at electrode potential U (V).

    Each proton-electron transfer shifts by +eU, so every step must be downhill for the reaction to run;
    the first U at which a step is uphill is the limiting potential.
    """
    steps = np.array([row["step1"], row["step2"], row["step3"], row["step4"]]) + U
    return pd.DataFrame({"state": ["O2 + 4(H+ + e-)", "*OOH", "*O", "*OH", "2 H2O"],
                         "G_eV": np.concatenate([[0.0], np.cumsum(steps)])})


def volcano_curve(dG_OH: np.ndarray, offset: float = OOH_OH_OFFSET) -> np.ndarray:
    """Textbook OOH-OH-only volcano: U_L = min(4.92 - offset - dG_OH, dG_OH).  Peaks at (4.92 - offset)/2."""
    return np.minimum(G_O2_TO_2H2O - offset - np.asarray(dG_OH, float), np.asarray(dG_OH, float))


def fit_scaling(df: pd.DataFrame, x="dG_OH", y="dG_OOH") -> dict:
    """Least-squares scaling relation y = m*x + b and its scatter (the physics check on a DFT table)."""
    d = df[[x, y]].dropna()
    if len(d) < 3:
        return {"n": len(d)}
    m, b = np.polyfit(d[x], d[y], 1)
    res = d[y] - (m * d[x] + b)
    ss_tot = ((d[y] - d[y].mean()) ** 2).sum()
    return {"n": len(d), "slope": float(m), "intercept": float(b), "rmse": float(np.sqrt((res ** 2).mean())),
            "r2": float(1 - (res ** 2).sum() / ss_tot) if ss_tot > 0 else float("nan")}


# --------------------------------------------------------------------------- elements and compositions
# Pauling electronegativity, valence d-electron count, fcc(-equivalent) lattice constant (A), standard
# reduction potential M^z+/M (V vs SHE, 25 C). Standard reference values; Fe and Co are not fcc at ambient
# conditions (lattice constants are fcc-equivalent), and bulk potentials are only a leaching *heuristic*.
ELEMENTS = {
    "Pt": dict(Z=78, chi=2.28, d=9, a=3.92, E0=1.18), "Pd": dict(Z=46, chi=2.20, d=10, a=3.89, E0=0.95),
    "Ir": dict(Z=77, chi=2.20, d=7, a=3.84, E0=1.16), "Rh": dict(Z=45, chi=2.28, d=8, a=3.80, E0=0.76),
    "Ru": dict(Z=44, chi=2.20, d=7, a=3.82, E0=0.455),
    "Au": dict(Z=79, chi=2.54, d=10, a=4.08, E0=1.50), "Ag": dict(Z=47, chi=1.93, d=10, a=4.09, E0=0.80),
    "Cu": dict(Z=29, chi=1.90, d=10, a=3.61, E0=0.34), "Ni": dict(Z=28, chi=1.91, d=8, a=3.52, E0=-0.257),
    "Co": dict(Z=27, chi=1.88, d=7, a=3.54, E0=-0.28), "Fe": dict(Z=26, chi=1.83, d=6, a=3.59, E0=-0.447),
}


def parse_composition(formula: str) -> dict[str, float]:
    """'Pt3Ni' -> {'Pt': 0.75, 'Ni': 0.25}; 'PtNi' -> 0.5/0.5; 'Pt' -> {'Pt': 1.0}."""
    parts = re.findall(r"([A-Z][a-z]?)(\d*\.?\d*)", formula.replace(" ", ""))
    amounts = {el: float(n) if n else 1.0 for el, n in parts if el}
    if not amounts or any(el not in ELEMENTS for el in amounts):
        raise ValueError(f"unsupported composition: {formula!r} (known elements: {sorted(ELEMENTS)})")
    tot = sum(amounts.values())
    return {el: v / tot for el, v in amounts.items()}


def composition_features(formula: str) -> dict[str, float]:
    """Cheap descriptors from composition only (no DFT): fraction-weighted means and spreads."""
    comp = parse_composition(formula)
    fr = np.array(list(comp.values()))
    f = {}
    for key, name in (("chi", "chi"), ("d", "dcount"), ("a", "lattice"), ("E0", "E0")):
        v = np.array([ELEMENTS[e][key] for e in comp])
        f[f"{name}_mean"] = float((fr * v).sum())
        f[f"{name}_min"] = float(v.min())
        f[f"{name}_range"] = float(v.max() - v.min())
    f["pt_fraction"] = comp.get("Pt", 0.0)
    f["lattice_mismatch_vs_Pt"] = f["lattice_mean"] / ELEMENTS["Pt"]["a"] - 1.0
    f["n_elements"] = float(len(comp))
    return f


def chemical_system(formula: str) -> str:
    """Sorted element set, e.g. 'Pt3Ni' and 'PtNi' -> 'Ni-Pt' (the group for leave-one-system-out)."""
    return "-".join(sorted(parse_composition(formula)))


def build_feature_table(df: pd.DataFrame) -> pd.DataFrame:
    """Features for ML: composition descriptors + facet one-hot + structure flag. No DFT-derived column."""
    rows = []
    for _, r in df.iterrows():
        f = composition_features(r["composition"])
        for fac in ("111", "100", "110"):
            f[f"facet_{fac}"] = float(str(r["facet"]) == fac)
        f["is_skin_or_overlayer"] = float(str(r.get("structure", "")).lower() in ("skin", "overlayer", "pt-skin"))
        rows.append(f)
    return pd.DataFrame(rows, index=df.index)


# --------------------------------------------------------------------------- validation
@dataclass
class ValidationReport:
    ok: bool
    errors: list
    warnings: list


def validate_table(df: pd.DataFrame) -> ValidationReport:
    err, warn = [], []
    miss = [c for c in REQUIRED_COLS if c not in df.columns]
    if miss:
        return ValidationReport(False, [f"missing columns: {miss}"], [])
    bad = set(df["provenance"].unique()) - set(PROVENANCE)
    if bad:
        err.append(f"unknown provenance values {sorted(bad)}; allowed: {PROVENANCE}")
    for c in ("E_OH", "E_O", "E_OOH"):
        if df[c].isna().any():
            err.append(f"{c} has missing values")
        elif not df[c].between(-6, 8).all():
            err.append(f"{c} has values outside [-6, 8] eV: check units and references (H2O/H2)")
    try:
        df["composition"].map(parse_composition)
    except ValueError as exc:
        err.append(str(exc))
    if df["system_id"].duplicated().any():
        err.append("duplicate system_id values")
    if (~df["provenance"].isin(TRUSTED)).any():
        warn.append("rows with untrusted provenance are present: the product will not recommend them")
    if "reference" in df and df.loc[df.provenance.isin(["dft", "literature_user"]), "reference"].isna().any():
        warn.append("dft / literature_user rows without a `reference` (cite your source)")
    return ValidationReport(not err, err, warn)


def load_dft_table(path) -> pd.DataFrame:
    """Read a DFT table you supply (see data/dft/README.md for the columns), validate it, add ORR metrics."""
    df = pd.read_csv(path)
    rep = validate_table(df)
    if not rep.ok:
        raise ValueError("; ".join(rep.errors))
    out = add_orr_metrics(df)
    out["chemical_system"] = out["composition"].map(chemical_system)
    out.attrs["warnings"] = rep.warnings
    return out


# --------------------------------------------------------------------------- stability heuristic
OPERATING_POTENTIAL = 0.9      # V, a typical PEMFC cathode potential near open circuit


def stability_flags(row: pd.Series, operating_potential: float = OPERATING_POTENTIAL) -> list[dict]:
    """Possible failure mechanisms with the evidence behind each flag (heuristics, not predictions)."""
    flags = []
    comp = parse_composition(row["composition"])
    skin = str(row.get("structure", "")).lower() in ("skin", "overlayer", "pt-skin")
    if "dissolution_potential" in row and pd.notna(row.get("dissolution_potential")):
        if row["dissolution_potential"] < operating_potential:
            flags.append({"mechanism": "dissolution", "evidence": "provided dissolution potential",
                          "detail": f"U_diss {row['dissolution_potential']:.2f} V < {operating_potential} V"})
    else:
        weak = [(e, ELEMENTS[e]["E0"]) for e in comp if ELEMENTS[e]["E0"] < operating_potential and e != "Pt"]
        if weak:
            flags.append({"mechanism": "leaching of the less noble metal",
                          "evidence": "textbook standard potential (heuristic, not DFT)",
                          "detail": ", ".join(f"{e} E0 = {v:+.2f} V" for e, v in weak) +
                                    (" (a Pt skin may protect it)" if skin else " exposed at the surface")})
    if pd.notna(row.get("segregation_energy")) and row["segregation_energy"] < 0:
        flags.append({"mechanism": "surface segregation", "evidence": "provided segregation energy",
                      "detail": f"{row['segregation_energy']:+.2f} eV favours the non-Pt element at the surface"})
    if row.get("pt_fraction", 1.0) < 0.5 and not skin:
        flags.append({"mechanism": "weak noble-metal protection", "evidence": "composition (heuristic)",
                      "detail": "Pt fraction below 0.5 without a skin"})
    return flags


# --------------------------------------------------------------------------- synthetic demo table
def make_demo_table(seed: int = 42) -> pd.DataFrame:
    """A TOY table so the pipeline and the app run with no data. Every row is `synthetic_demo`.

    Adsorption energies come from an invented linear model of composition descriptors plus noise.
    They are NOT the output of any DFT code and must never be quoted or used to choose a catalyst.
    """
    rng = np.random.default_rng(seed)
    rows, k = [], 0
    for m in ["Ni", "Co", "Fe", "Cu", "Pd", "Ir", "Rh", "Au", "Ag"]:
        for formula in (f"Pt3{m}", f"Pt{m}", "Pt"):
            if formula == "Pt" and m != "Ni":
                continue
            for facet in ("111", "100", "110"):
                for structure in (("bulk", "skin") if formula != "Pt" else ("bulk",)):
                    f = composition_features(formula)
                    d_chi = f["chi_mean"] - ELEMENTS["Pt"]["chi"]
                    strain = f["lattice_mismatch_vs_Pt"]
                    off = {"111": 0.0, "100": -0.12, "110": -0.2}[facet]
                    skin = 1.0 if structure == "skin" else 0.0
                    e_oh = 0.60 + 0.9 * d_chi + 3.0 * strain * (1 + skin) + off + rng.normal(0, 0.05)
                    e_o = 2.0 * e_oh + 0.60 + rng.normal(0, 0.10)
                    e_ooh = e_oh + 3.15 + rng.normal(0, 0.08)
                    rows.append({"system_id": f"DEMO-{k:03d}", "composition": formula, "facet": facet, "structure": structure,
                                 "E_OH": e_oh, "E_O": e_o, "E_OOH": e_ooh,
                                 "d_band_center": -2.3 - 1.2 * d_chi + 4.0 * strain + rng.normal(0, 0.05),
                                 "provenance": "synthetic_demo", "reference": "toy model, not a result"})
                    k += 1
    return pd.DataFrame(rows)
